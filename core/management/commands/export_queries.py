"""
Writes the SQL behind every SELECT in core/queries.py to database/queries.sql.

    python manage.py export_queries

The SQL is generated by Django from the same functions the views call, using sample
values, so the file always matches what the system actually runs (spec 3.2).
"""
from datetime import date, datetime
from pathlib import Path

from django.conf import settings
from django.contrib.auth.models import User
from django.core.management.base import BaseCommand
from django.utils import timezone

from core import queries
from core.models import AmenityType, Building, Venue


def _quote(value):
    if value is None:
        return 'NULL'
    if isinstance(value, bool):
        return '1' if value else '0'
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, (datetime, date)):
        value = value.isoformat(sep=' ') if isinstance(value, datetime) else value.isoformat()
    return "'" + str(value).replace("'", "''") + "'"


def to_sql(queryset):
    # Django keeps values separate from the SQL (%s placeholders); fill them in for display only.
    sql, params = queryset.query.sql_with_params()
    return sql % tuple(_quote(p) for p in params)


class Command(BaseCommand):
    help = 'Export the SELECT statements used by the views to database/queries.sql'

    def handle(self, *args, **options):
        # Sample inputs, as if a customer had typed them into the page.
        building = Building(pk='BLDG1001')
        amenity = AmenityType(pk='AMTY1001')
        venue = Venue(pk='00001001')
        user = User(pk=1)
        start = timezone.make_aware(datetime(2027, 1, 10, 10, 0))
        end = timezone.make_aware(datetime(2027, 1, 10, 11, 0))
        today = date(2027, 1, 10)

        statements = [
            ('Venue list filter: building dropdown options',
             'GET /venues/',
             queries.building_options()),
            ('Venue list filter: venue type dropdown options',
             'GET /venues/',
             queries.venue_type_options()),
            ('Venue list filter: amenity dropdown options',
             'GET /venues/',
             queries.amenity_options()),
            ('Venue search by building, type, capacity and amenity',
             'GET /venues/?building=BLDG1001&type=Gym&min_capacity=100&amenities=AMTY1001',
             queries.search_venues(building=building, venue_type='Gym',
                                   min_capacity=100, amenities=[amenity])),
            ('Available venues: no overlapping reservation or renovation',
             'GET /venues/?start=2027-01-10T10:00&end=2027-01-10T11:00',
             queries.search_venues(start=start, end=end)),
            ('Venue details with its building',
             'GET /venues/00001001/',
             queries.venue_with_building().filter(pk=venue.pk)),
            ('Amenities installed in the venue',
             'GET /venues/00001001/',
             queries.venue_amenities(venue)),
            ('Agent currently assigned to the venue',
             'GET /venues/00001001/',
             queries.current_agent_assignment(venue, today=today)[:1]),
            ('Ongoing renovations of the venue',
             'GET /venues/00001001/',
             queries.ongoing_renovations(venue, today=today)),
            ("Logged-in customer's reservations",
             'GET /reservations/',
             queries.customer_reservations(user)),
            ('Reservation summary (own reservations only)',
             'GET /reservations/RSVN1001/',
             queries.customer_reservations(user).filter(pk='RSVN1001')),
        ]

        lines = [
            '-- CSCI 41: Venue Management Database',
            '-- SELECT statements used by the system (generated by: python manage.py export_queries)',
            '-- Values are samples. In the app they come from the URL or the logged-in user.',
            '',
        ]
        for number, (title, url, queryset) in enumerate(statements, start=1):
            lines += [f'-- {number}. {title}', f'-- Used by: {url}', to_sql(queryset) + ';', '']

        output = Path(settings.BASE_DIR) / 'database' / 'queries.sql'
        output.write_text('\n'.join(lines), encoding='utf-8')
        self.stdout.write(self.style.SUCCESS(f'Wrote {len(statements)} SELECT statements to {output}'))
